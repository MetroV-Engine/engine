#include "Renderer/BasePath/BasePath.hpp"

#include <SDL3/SDL.h>

namespace tools {

    std::string pathNextToExecutable(const std::string_view relative)
    {
        const char* base = SDL_GetBasePath();

        return std::string(base != nullptr ? base : "") + std::string(relative);
    }

}
